using Xunit;
using Xunit.Abstractions;

namespace OracleSqlParser.IntegrationTests;

/// <summary>
/// Proves SqlScriptGenerator against a real Oracle. For every corpus statement that Oracle accepts as written
/// (Executed or SyntaxAcceptedSemanticError), the statement is parsed, regenerated with each option set (defaults,
/// fully formatted, lower case) and the generated text is run in a fresh scratch user. Oracle must classify it the same
/// way: Executed stays Executed; SyntaxAcceptedSemanticError may become Executed (or stay) but never Rejected.
/// </summary>
[Collection(OracleCollection.Name)]
public class GeneratorAcceptanceTests(OracleFixture db, ITestOutputHelper output)
{
    /// <summary>
    /// Statements whose generated form Oracle rejects for a known reason. Key = "optionSet|original sql". The test asserts
    /// each entry is still accurate (Oracle still rejects it). Must stay empty unless a gap is explained here.
    /// </summary>
    public static readonly Dictionary<string, string> KnownGeneratorGaps = new();

    private static readonly Dictionary<int, (Outcome, string)> OriginalOutcomes = [];

    private static string Prefix(string optionSet) => optionSet switch { "defaults" => "GD", "formatted" => "GF", _ => "GL" };

    public static IEnumerable<object[]> Cases() =>
        CorpusAcceptanceTests.Corpus().Select((s, i) => (s, i))
            .SelectMany(p => GeneratorOptionSets.All.Select(o => new object[] { p.i, p.s, o.Name }));

    private async Task<(Outcome, string)> OriginalOutcome(int index, string sql)
    {
        if (OriginalOutcomes.TryGetValue(index, out var cached)) return cached;
        var r = await OracleHarness.RunInScratchSchema(db, $"GO{index}", OracleHarness.Prepare(sql), false);
        OriginalOutcomes[index] = r;
        return r;
    }

    [SkippableTheory]
    [MemberData(nameof(Cases))]
    public async Task GeneratedStatement_IsClassifiedLikeOriginal(int index, string sql, string optionSet)
    {
        db.SkipIfUnavailable();
        Skip.If(CorpusAcceptanceTests.NotExecutable.ContainsKey(sql), "not a single Oracle statement");
        Skip.If(CorpusAcceptanceTests.PlsqlOnlyForms.ContainsKey(sql) || CorpusAcceptanceTests.KnownOracleRejects.ContainsKey(sql),
            "Oracle rejects the original");

        var (original, originalDetail) = await OriginalOutcome(index, sql);
        Skip.If(original is not (Outcome.Executed or Outcome.SyntaxAcceptedSemanticError), $"original outcome {original}");

        var parsed = SqlParser.Parse(sql);
        Assert.True(parsed.Success, $"parser rejected: {string.Join("; ", parsed.Errors)}");
        var generator = new SqlScriptGenerator(GeneratorOptionSets.Get(optionSet)());

        // A one-statement script is run as generated by Generate(script) (with its terminator);
        // longer scripts are split and run statement by statement, like a client would.
        var texts = parsed.Script.Statements.Count == 1
            ? [generator.Generate(parsed.Script)]
            : parsed.Script.Statements.Select(s => generator.Generate(s)).ToList();

        var user = $"{Prefix(optionSet)}{index}";
        var worst = Outcome.Executed;
        string detail = "ok", generatedText = "";
        foreach (var text in texts)
        {
            var (o, d) = await OracleHarness.RunInScratchSchema(db, user, OracleHarness.Prepare(text), false);
            if (o == Outcome.Rejected) { worst = o; detail = d; generatedText = text; break; }
            if (o == Outcome.SyntaxAcceptedSemanticError) { worst = o; detail = d; generatedText = text; }
        }
        output.WriteLine($"GENERATED set={optionSet} original={original} generated={worst} detail={detail}\nORIGINAL:  {sql}\nGENERATED: {string.Join("\n", texts)}");

        var gapKey = $"{optionSet}|{sql}";
        if (KnownGeneratorGaps.TryGetValue(gapKey, out var gap))
        {
            Assert.True(worst == Outcome.Rejected, $"known generator gap ({gap}) no longer reproduces; remove it. Outcome {worst}");
            return;
        }
        Assert.True(worst != Outcome.Rejected,
            $"Oracle rejected generated SQL ({optionSet}).\nORIGINAL ({original}: {originalDetail}):\n{sql}\nGENERATED:\n{generatedText}\n{detail}");
        if (original == Outcome.Executed)
            Assert.True(worst == Outcome.Executed, $"original Executed but generated ({optionSet}) is {worst}: {detail}\nGENERATED:\n{generatedText}");
    }

    [Fact]
    public void KnownGeneratorGaps_AreDocumented() => Assert.All(KnownGeneratorGaps, kv => Assert.False(string.IsNullOrWhiteSpace(kv.Value)));
}
