using System.Reflection;
using System.Text;

namespace AstGen;

/// <summary>
/// Generates the per-node plumbing (GetChildren, Accept, AcceptChildren, rewriting, cloning, structural comparison,
/// and the typed visitor/rewriter methods) by reflecting over a built OracleSqlParser assembly.
/// The assembly is inspected by name only (this project does not reference it), so the generator builds and runs
/// even when the library's Generated/ folder is empty or stale.
/// </summary>
public static class AstGenerator
{
    private enum Kind { Node, List, Nested, Strings, Scalar }

    private sealed record Prop(string Name, Kind Kind, string? Element, bool Nullable, bool SpellingOnly);

    /// <summary>Returns file name to file content for every generated file.</summary>
    public static IReadOnlyDictionary<string, string> Generate(Assembly library)
    {
        var sqlNode = library.GetType("OracleSqlParser.SqlNode") ?? throw new InvalidOperationException("OracleSqlParser.SqlNode not found");
        var types = library.GetTypes()
            .Where(t => t.IsPublic && t.IsClass && !t.IsAbstract && t.IsSubclassOf(sqlNode))
            .OrderBy(t => t.Name, StringComparer.Ordinal)
            .ToList();

        var nodes = new StringBuilder();
        Header(nodes);
        nodes.Append("namespace OracleSqlParser;\n");
        foreach (var t in types) EmitNode(nodes, t, sqlNode);

        var visitor = new StringBuilder();
        Header(visitor);
        visitor.Append("namespace OracleSqlParser;\n\npublic abstract partial class SqlNodeVisitor\n{");
        bool first = true;
        foreach (var t in types)
        {
            if (!first) visitor.Append('\n');
            first = false;
            visitor.Append($"\n    /// <summary>Called for a <see cref=\"{t.Name}\"/>. The default forwards to <see cref=\"Visit(SqlNode)\"/>.</summary>\n");
            visitor.Append($"    public virtual void Visit({t.Name} node) => Visit((SqlNode)node);\n\n");
            visitor.Append($"    /// <summary>Entry point for a <see cref=\"{t.Name}\"/>. The default calls <c>Visit(node)</c> and then visits the children.</summary>\n");
            visitor.Append($"    public virtual void ExplicitVisit({t.Name} node)\n    {{\n        Visit(node);\n        node.AcceptChildren(this);\n    }}");
        }
        visitor.Append("\n}\n");

        var rewriter = new StringBuilder();
        Header(rewriter);
        rewriter.Append("namespace OracleSqlParser;\n\npublic abstract partial class SqlNodeRewriter\n{");
        first = true;
        foreach (var t in types)
        {
            if (!first) rewriter.Append('\n');
            first = false;
            rewriter.Append($"\n    /// <summary>Rewrites a <see cref=\"{t.Name}\"/>: by default rewrites its children and returns it. Return another node to replace it, or null to remove it.</summary>\n");
            rewriter.Append($"    public virtual SqlNode? Rewrite({t.Name} node)\n    {{\n        node.RewriteChildren(this);\n        return node;\n    }}");
        }
        rewriter.Append("\n}\n");

        return new Dictionary<string, string>
        {
            ["Nodes.g.cs"] = nodes.ToString(),
            ["SqlNodeVisitor.g.cs"] = visitor.ToString(),
            ["SqlNodeRewriter.g.cs"] = rewriter.ToString(),
        };
    }

    private static void Header(StringBuilder sb) =>
        sb.Append("// <auto-generated>\n// Generated by tools/AstGen (dotnet run --project tools/AstGen). Do not edit.\n// </auto-generated>\n\n#nullable enable\n\n");

    /// <summary>Public instance properties declared below SqlNode, in declaration order: exactly the set SqlNode.Children() has always used.</summary>
    private static List<Prop> Discover(Type type, Type sqlNode)
    {
        var ctx = new NullabilityInfoContext();
        var list = new List<Prop>();
        foreach (var p in type.GetProperties(BindingFlags.Public | BindingFlags.Instance)
                     .Where(p => p.DeclaringType != sqlNode && p.GetIndexParameters().Length == 0))
        {
            if (p.GetSetMethod() is null) throw new InvalidOperationException($"{type.Name}.{p.Name} has no public setter");
            var pt = p.PropertyType;
            bool spelling = p.GetCustomAttributesData().Any(a => a.AttributeType.Name == "SpellingOnlyAttribute");
            bool nullable = ctx.Create(p).ReadState == NullabilityState.Nullable;
            if (sqlNode.IsAssignableFrom(pt))
                list.Add(new Prop(p.Name, Kind.Node, pt.Name, nullable, spelling));
            else if (pt.IsGenericType && pt.GetGenericTypeDefinition() == typeof(List<>))
            {
                var el = pt.GetGenericArguments()[0];
                if (el == typeof(string)) list.Add(new Prop(p.Name, Kind.Strings, null, nullable, spelling));
                else if (sqlNode.IsAssignableFrom(el)) list.Add(new Prop(p.Name, Kind.List, el.Name, nullable, spelling));
                else if (el.IsGenericType && el.GetGenericTypeDefinition() == typeof(List<>) && sqlNode.IsAssignableFrom(el.GetGenericArguments()[0]))
                    list.Add(new Prop(p.Name, Kind.Nested, el.GetGenericArguments()[0].Name, nullable, spelling));
                else throw new InvalidOperationException($"{type.Name}.{p.Name}: unsupported list type {pt}");
            }
            else
            {
                var u = Nullable.GetUnderlyingType(pt) ?? pt;
                if (u == typeof(string) || u == typeof(bool) || u == typeof(int) || u == typeof(char) || u.IsEnum)
                    list.Add(new Prop(p.Name, Kind.Scalar, null, nullable, spelling));
                else throw new InvalidOperationException($"{type.Name}.{p.Name}: unsupported property type {pt}");
            }
        }
        return list;
    }

    private static void EmitNode(StringBuilder sb, Type t, Type sqlNode)
    {
        var props = Discover(t, sqlNode);
        var n = t.Name;
        var children = props.Where(p => p.Kind is Kind.Node or Kind.List or Kind.Nested).ToList();
        var key = (string x) => $"\"{n}.{x}\"";

        sb.Append($"\npublic partial class {n}\n{{\n");

        if (children.Count > 0)
        {
            sb.Append("    /// <inheritdoc/>\n    public override IEnumerable<SqlNode> GetChildren()\n    {\n");
            foreach (var p in children)
            {
                switch (p.Kind)
                {
                    case Kind.Node: sb.Append($"        if ({p.Name} is not null) yield return {p.Name};\n"); break;
                    case Kind.List: sb.Append($"        if ({p.Name} is not null) foreach (var x in {p.Name}) yield return x;\n"); break;
                    case Kind.Nested: sb.Append($"        if ({p.Name} is not null) foreach (var row in {p.Name}) if (row is not null) foreach (var x in row) yield return x;\n"); break;
                }
            }
            sb.Append("    }\n\n");

            sb.Append("    /// <inheritdoc/>\n    public override void AcceptChildren(SqlNodeVisitor visitor)\n    {\n");
            foreach (var p in children)
            {
                switch (p.Kind)
                {
                    case Kind.Node: sb.Append($"        {p.Name}?.Accept(visitor);\n"); break;
                    case Kind.List: sb.Append($"        if ({p.Name} is not null) foreach (var x in {p.Name}) x.Accept(visitor);\n"); break;
                    case Kind.Nested: sb.Append($"        if ({p.Name} is not null) foreach (var row in {p.Name}) if (row is not null) foreach (var x in row) x.Accept(visitor);\n"); break;
                }
            }
            sb.Append("    }\n\n");

            sb.Append("    internal override void RewriteChildren(SqlNodeRewriter rewriter)\n    {\n");
            foreach (var p in children)
            {
                switch (p.Kind)
                {
                    case Kind.Node when p.Nullable: sb.Append($"        {p.Name} = SqlNodeRewriter.RewriteOptional(rewriter, {p.Name}, {key(p.Name)});\n"); break;
                    case Kind.Node: sb.Append($"        {p.Name} = SqlNodeRewriter.RewriteRequired(rewriter, {p.Name}, {key(p.Name)});\n"); break;
                    case Kind.List: sb.Append($"        SqlNodeRewriter.RewriteList(rewriter, {p.Name}, {key(p.Name)});\n"); break;
                    case Kind.Nested: sb.Append($"        SqlNodeRewriter.RewriteNested(rewriter, {p.Name}, {key(p.Name)});\n"); break;
                }
            }
            sb.Append("    }\n\n");
        }

        sb.Append("    /// <inheritdoc/>\n    public override void Accept(SqlNodeVisitor visitor) => visitor.ExplicitVisit(this);\n\n");
        sb.Append("    internal override SqlNode? AcceptRewriter(SqlNodeRewriter rewriter) => rewriter.Rewrite(this);\n\n");

        sb.Append($"    internal override SqlNode CloneCore()\n    {{\n        var c = new {n}();\n        CopySpan(this, c);\n");
        foreach (var p in props)
        {
            switch (p.Kind)
            {
                case Kind.Scalar: sb.Append($"        c.{p.Name} = {p.Name};\n"); break;
                case Kind.Strings: sb.Append($"        c.{p.Name} = CloneStrings({p.Name});\n"); break;
                case Kind.Node: sb.Append($"        c.{p.Name} = CloneChild({p.Name}){(p.Nullable ? "" : "!")};\n"); break;
                case Kind.List: sb.Append($"        c.{p.Name} = CloneList({p.Name});\n"); break;
                case Kind.Nested: sb.Append($"        c.{p.Name} = CloneNested({p.Name});\n"); break;
            }
        }
        sb.Append("        return c;\n    }\n");

        var compared = props.Where(p => !p.SpellingOnly).ToList();
        if (compared.Count > 0)
        {
            sb.Append($"\n    internal override bool ShapeEquals(SqlNode other, Stack<(SqlNode, SqlNode)> pending)\n    {{\n        var o = ({n})other;\n        return ");
            var terms = new List<string>();
            foreach (var p in compared)
            {
                terms.Add(p.Kind switch
                {
                    Kind.Scalar => $"{p.Name} == o.{p.Name}",
                    Kind.Strings => $"SameStrings({p.Name}, o.{p.Name})",
                    Kind.Node => $"Pair({p.Name}, o.{p.Name}, pending)",
                    Kind.List => $"PairList({p.Name}, o.{p.Name}, pending)",
                    _ => $"PairNested({p.Name}, o.{p.Name}, pending)",
                });
            }
            sb.Append(string.Join("\n            && ", terms)).Append(";\n    }\n");
        }
        sb.Append("}\n");
    }
}
